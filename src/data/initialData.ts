export function getInitialMonths(): MonthRecord[] {
  return RAW_MONTHS.map((rm) => {
    const monthIndex = rm.month - 1;
    const formattedMonth = String(rm.month).padStart(2, '0');
    const id = `${rm.year}-${formattedMonth}`;
    
    const dailyEntries: DailyEntry[] = (rm.days || []).map((d, idx) => {
      const dayNum = d[0];
      const val = d[1];
      const note = d[2];
      const formattedDay = String(dayNum).padStart(2, '0');
      return {
        id: `${id}-${formattedDay}-${idx}`,
        date: `${rm.year}-${formattedMonth}-${formattedDay}`,
        day: dayNum,
        value: val,
        notes: note
      };
    });

    return {
      id,
      year: rm.year,
      monthIndex,
      monthLabel: `${MONTH_SHORT[monthIndex]}/${String(rm.year).slice(-2)}`,
      total: rm.total,
      daysCount: dailyEntries.length,
      dailyEntries,
      notes: rm.extraNotes || [],
      aluguel: rm.aluguel
    };
  });
}
